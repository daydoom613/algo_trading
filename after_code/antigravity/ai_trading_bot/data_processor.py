def get_data(ticker, start, end):
    """
    Wrapper to fetch data. In a production environment for 2015-2023 intraday data,
    this function would load from local CSVs (e.g., Kaggle datasets) rather than yfinance.
    For this demonstration, we use yfinance daily data which is available for the full range.
    """
    print(f"Fetching data for {ticker} from {start} to {end}...")
    # Using auto_adjust=True to get Adjusted Close implicitly if needed, 
    # but yfinance standard download often works best with explicit columns.
    df = yf.download(ticker, start=start, end=end, progress=False)
    if df.empty:
        raise ValueError("No data fetched. Check ticker or internet connection.")
    return df

def add_technical_indicators(df):
    """
    Computes RSI, MACD, and Bollinger Bands to create stationary features.
    """
    # Ensure we are working with a copy to avoid SettingWithCopy warnings
    df = df.copy()
    
    # Handle potential MultiIndex columns from yfinance (Ticker as level 0)
    # Handle potential MultiIndex columns from yfinance
    if isinstance(df.columns, pd.MultiIndex):
        # Check which level has 'Close'
        if 'Close' in df.columns.get_level_values(0):
            df.columns = df.columns.get_level_values(0)
        else:
             df.columns = df.columns.get_level_values(-1)

    # 1. RSI (14 periods)
    delta = df['Close'].diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
    rs = gain / loss
    df['RSI'] = 100 - (100 / (1 + rs))
    
    # 2. MACD
    ema12 = df['Close'].ewm(span=12, adjust=False).mean()
    ema26 = df['Close'].ewm(span=26, adjust=False).mean()
    df['MACD'] = ema12 - ema26
    df['Signal_Line'] = df['MACD'].ewm(span=9, adjust=False).mean()
    
    # 3. Bollinger Bands
    sma20 = df['Close'].rolling(window=20).mean()
    std20 = df['Close'].rolling(window=20).std()
    df['Upper'] = sma20 + (std20 * 2)
    df['Lower'] = sma20 - (std20 * 2)
    # %B Feature: Normalized price position within bands
    df['PctB'] = (df['Close'] - df['Lower']) / (df['Upper'] - df['Lower'])
    
    # Drop NaN values generated by rolling windows
    df.dropna(inplace=True)
    return df

def create_labels(df, horizon=1, threshold=0.01):
    """
    Generates labels based on future returns.
    0: Hold, 1: Buy, 2: Sell
    """
    # Calculate future return (Lookahead)
    df['Future_Return'] = df['Close'].shift(-horizon) / df['Close'] - 1
    
    conditions = [
        (df['Future_Return'] > threshold),  # Buy
        (df['Future_Return'] < -threshold)  # Sell
    ]
    choices = [1, 2]
    # Default is 0 (Hold)
    df['Label'] = np.select(conditions, choices, default=0)
    
    # Drop the last 'horizon' rows as they have no future return
    df.dropna(subset=['Future_Return'], inplace=True)
    return df

def create_sequences(features, labels, seq_len):
    X, y = [], []
    for i in range(seq_len, len(features)):
        X.append(features[i-seq_len:i])
        y.append(labels[i])
    return np.array(X), np.array(y)
